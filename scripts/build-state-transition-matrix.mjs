const known = new Set(entries.map((entry) => entry.code));
for (const [from, targets] of allowed) {
  if (!known.has(from) || targets.some((target) => !known.has(target))) {
    throw new Error("상태 전환표가 알 수 없는 상태를 참조한다: " + from + " -> " + targets.join(","));
  }
}

const states = entries.map((entry) => {
  const allowedTargets = [...new Set(allowed.get(entry.code) ?? [])];
  const sameAxis = byAxis.get(entry.axis) ?? [];
  const representativeForbiddenTargets = sameAxis
    .filter((target) => target !== entry.code && !allowedTargets.includes(target))
    .slice(0, 1);
  return {
    axis: entry.axis,
    stateCode: entry.code,
    labelKo: entry.labelKo,
    allowedTargets,
    representativeForbiddenTargets,
    forbiddenErrorCode: representativeForbiddenTargets.length ? "STATE_CONFLICT" : null,
    source: "../../05-screens-states-recovery/STATE_MODEL.md",
  };
});

const output = await format(
  JSON.stringify({
    $schema: "./state-transition-matrix.schema.json",
    schemaVersion: "1.0.0",
    sourceCatalog: "../../07-data-api-events/specs/state-catalog.json",
    sourceDesign: "../../05-screens-states-recovery/STATE_MODEL.md",
    totalStates: states.length,
    states,
  }),
  {
    ...(await resolveConfig(
      resolve(root, "docs/10-poc-implementation/specs/state-transition-matrix.json"),
    )),
    parser: "json",
  },
);
await writeFile(
  resolve(root, "docs/10-poc-implementation/specs/state-transition-matrix.json"),
  output,
  "utf8",
);

